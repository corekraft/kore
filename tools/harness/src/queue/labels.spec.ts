import { describe, expect, it } from "vitest";
import {
  GRILL_PREFIX,
  HARNESS_LABEL,
  HORIZON_NEXT_LABEL,
  HORIZON_THEN_LABEL,
  IDEA_MARKER,
  PAUSED_LABEL,
  READY_LABEL,
  SPEC_LABEL,
} from "./labels.js";

// These strings are the owner's label vocabulary and the banner idea sync writes;
// the frontier rule matches them exactly, so a change here is a change to the queue.
describe("the frontier's label and marker vocabulary", () => {
  it("names the labels the owner applies, exactly", () => {
    expect({
      READY_LABEL,
      PAUSED_LABEL,
      SPEC_LABEL,
      HARNESS_LABEL,
      HORIZON_NEXT_LABEL,
      HORIZON_THEN_LABEL,
    }).toEqual({
      READY_LABEL: "ready-for-agent",
      PAUSED_LABEL: "paused",
      SPEC_LABEL: "spec",
      HARNESS_LABEL: "harness",
      HORIZON_NEXT_LABEL: "horizon:next",
      HORIZON_THEN_LABEL: "horizon:then",
    });
  });

  it("matches the banner harness idea sync writes at the top of an idea issue", () => {
    expect(IDEA_MARKER).toBe("<!-- Generated by `harness idea sync`");
  });

  it("matches the prefix a grilling session gives the issue it files", () => {
    expect(GRILL_PREFIX).toBe("Filed by ");
  });
});
