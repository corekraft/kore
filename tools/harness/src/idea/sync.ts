import type { Runner } from "../runtime/index.js";
import { IdeaError, type IdeaRecord } from "./record.js";

export type SyncAction = "created" | "updated" | "unchanged";

export interface SyncResult {
  action: SyncAction;
  issue: string;
}

/** gh's answer for a missing issue; a missing repository or a network failure must not match. */
const NOT_FOUND = /could not resolve to an issue|issue .*not found|no issue/i;
const ISSUE_URL = /https:\/\/github\.com\/([\w.-]+\/[\w.-]+)\/issues\/(\d+)/;

/** Everything in the markdown after its first heading: the author's own prose. */
function prose(text: string): string {
  const lines = text.split("\n");
  const at = lines.findIndex((l) => /^# Idea \d{4}: /.test(l));
  return (at === -1 ? "" : lines.slice(at + 1).join("\n")).trim();
}

/** The issue body, a pure function of the markdown: edits made on GitHub never feed back. */
export function renderBody(record: IdeaRecord, text: string): string {
  const sections = [
    `<!-- Generated by \`harness idea sync\` from ${record.path}. Edit that file; changes made here are overwritten. -->`,
    `## Summary\n\n${record.summary}`,
    `## Hypothesis\n\n${record.hypothesis}`,
    `## Expected outcome\n\n${record.expectedOutcome}`,
    `## Measurement\n\n${record.measurement}`,
    `## Safety pattern\n\n${record.safetyPattern}`,
  ];
  const extra = prose(text);
  if (extra !== "") {
    sections.push(extra);
  }
  return `${sections.join("\n\n")}\n`;
}

const normal = (value: string) => value.replace(/\r\n/g, "\n").trimEnd();

/** Where an idea's recorded issue lives: its number, and its repository when the link names one. */
function locate(issue: string): { number: string; repo: string[] } | undefined {
  const url = ISSUE_URL.exec(issue);
  if (url?.[1] !== undefined && url[2] !== undefined) {
    return { number: url[2], repo: ["--repo", url[1]] };
  }
  const bare = /^#?(\d+)$/.exec(issue.trim());
  return bare?.[1] === undefined ? undefined : { number: bare[1], repo: [] };
}

type Gh = (
  args: string[],
  input?: string,
) => Promise<{ stdout: string; stderr: string; code: number }>;

const fix = "Check `gh auth status` and rerun `harness idea sync`.";

/** Brings an existing issue in line with the markdown, writing only when it differs. */
async function reconcile(
  gh: Gh,
  record: IdeaRecord,
  body: string,
  at: { number: string; repo: string[] },
): Promise<SyncResult | undefined> {
  const issue = record.issue ?? "";
  const view = await gh([
    "issue",
    "view",
    at.number,
    ...at.repo,
    "--json",
    "title,body",
  ]);
  if (view.code !== 0) {
    if (NOT_FOUND.test(view.stderr)) {
      return undefined;
    }
    throw new IdeaError(
      `gh could not read issue ${issue}: ${view.stderr.trim()}. ${fix}`,
    );
  }
  const current = parseView(view.stdout, issue);
  if (current.title === record.title && normal(current.body) === normal(body)) {
    return { action: "unchanged", issue };
  }
  const edit = await gh(
    [
      "issue",
      "edit",
      at.number,
      ...at.repo,
      "--title",
      record.title,
      "--body-file",
      "-",
    ],
    body,
  );
  if (edit.code !== 0) {
    throw new IdeaError(
      `gh could not update issue ${issue}: ${edit.stderr.trim()}. ${fix}`,
    );
  }
  return { action: "updated", issue };
}

/**
 * Mirrors an idea to its GitHub issue in one direction. The issue is read only to
 * decide whether a write is needed; only the title and body are ever written, never
 * labels or assignees.
 */
export async function syncIssue(
  runner: Runner,
  root: string,
  record: IdeaRecord,
  text: string,
  recordLink: (url: string) => Promise<void>,
): Promise<SyncResult> {
  const body = renderBody(record, text);
  const gh: Gh = async (args, input) =>
    await runner.run("gh", args, {
      cwd: root,
      ...(input === undefined ? {} : { input }),
    });
  const at = record.issue === undefined ? undefined : locate(record.issue);
  if (record.issue !== undefined && at === undefined) {
    throw new IdeaError(
      `${record.path} has issue "${record.issue}", which is not an issue number or link; set it to e.g. 123 or https://github.com/<owner>/<repo>/issues/123.`,
    );
  }
  const existing =
    at === undefined ? undefined : await reconcile(gh, record, body, at);
  if (existing !== undefined) {
    return existing;
  }
  const created = await gh(
    [
      "issue",
      "create",
      ...(at?.repo ?? []),
      "--title",
      record.title,
      "--body-file",
      "-",
    ],
    body,
  );
  const url = ISSUE_URL.exec(created.stdout)?.[0];
  if (created.code !== 0 || url === undefined) {
    throw new IdeaError(
      `gh did not create the issue or print an issue link: ${(created.stderr || created.stdout).trim()}. ${fix}`,
    );
  }
  try {
    await recordLink(url);
  } catch (error) {
    throw new IdeaError(
      `Created ${url} but could not record it in ${record.path}: ${error instanceof Error ? error.message : String(error)}. Add \`issue: ${url}\` to its frontmatter, then rerun \`harness idea sync\`; otherwise a second issue is created.`,
    );
  }
  return { action: "created", issue: url };
}

function parseView(
  stdout: string,
  issue: string,
): { title: string; body: string } {
  try {
    const parsed = JSON.parse(stdout) as { title?: unknown; body?: unknown };
    return {
      title: typeof parsed.title === "string" ? parsed.title : "",
      body: typeof parsed.body === "string" ? parsed.body : "",
    };
  } catch {
    throw new IdeaError(
      `gh returned unreadable output for issue ${issue}; rerun \`harness idea sync\`.`,
    );
  }
}
