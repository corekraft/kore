import type { Runner } from "../runtime/index.js";
import { IdeaError, withoutOutcome, type IdeaRecord } from "./record.js";

export type SyncAction = "created" | "updated" | "unchanged";

export interface SyncResult {
  action: SyncAction;
  issue: string;
}

/** gh's answer for a missing issue; a missing repository or a network failure must not match. */
const NOT_FOUND = /could not resolve to an issue|issue .*not found|no issue/i;
const ISSUE_URL = /https:\/\/github\.com\/([\w.-]+\/[\w.-]+)\/issues\/(\d+)/;

/** Everything in the markdown after its first heading: the author's own prose, never the recorded outcome. */
function prose(text: string): string {
  const lines = withoutOutcome(text).split("\n");
  const at = lines.findIndex((l) => /^# Idea \d{4}: /.test(l));
  return (at === -1 ? "" : lines.slice(at + 1).join("\n")).trim();
}

/** The issue body, a pure function of the markdown: edits made on GitHub never feed back. */
export function renderBody(record: IdeaRecord, text: string): string {
  const sections = [
    `<!-- Generated by \`harness idea sync\` from ${record.path}. Edit that file; changes made here are overwritten. -->`,
    `## Summary\n\n${record.summary}`,
    `## Hypothesis\n\n${record.hypothesis}`,
    `## Expected outcome\n\n${record.expectedOutcome}`,
    `## Measurement\n\n${record.measurement}`,
    `## Safety pattern\n\n${record.safetyPattern}`,
  ];
  const extra = prose(text);
  if (extra !== "") {
    sections.push(extra);
  }
  return `${sections.join("\n\n")}\n`;
}

const normal = (value: string) => value.replace(/\r\n/g, "\n").trimEnd();

/** Where an idea's recorded issue lives: its number, and its repository when the link names one. */
function locate(issue: string): { number: string; repo?: string } | undefined {
  const url = ISSUE_URL.exec(issue);
  if (url?.[1] !== undefined && url[2] !== undefined) {
    return { number: url[2], repo: url[1] };
  }
  const bare = /^#?(\d+)$/.exec(issue.trim());
  return bare?.[1] === undefined ? undefined : { number: bare[1] };
}

const REPO_PROBLEM = /repositor/i;

/** The failure text with a fix: no auth hint when gh blames the repository. */
function failure(what: string, stderr: string): IdeaError {
  const hint = REPO_PROBLEM.test(stderr)
    ? "Check the repository named above, then rerun `harness idea sync`."
    : fix;
  return new IdeaError(`${what}: ${stderr.trim()}. ${hint}`);
}

/** The repository every gh call names: from the recorded link, else the checkout's own, asked once. */
async function resolveRepo(gh: Gh, recorded?: string): Promise<string> {
  if (recorded !== undefined) {
    return recorded;
  }
  const view = await gh(["repo", "view", "--json", "nameWithOwner"]);
  let name: unknown;
  try {
    name = (JSON.parse(view.stdout) as { nameWithOwner?: unknown })
      .nameWithOwner;
  } catch {
    name = undefined;
  }
  if (view.code !== 0 || typeof name !== "string" || name === "") {
    throw failure("gh could not tell which repository this is", view.stderr);
  }
  return name;
}

type Gh = (
  args: string[],
  input?: string,
) => Promise<{ stdout: string; stderr: string; code: number }>;

const fix = "Check `gh auth status` and rerun `harness idea sync`.";

/** Brings an existing issue in line with the markdown, writing only when it differs. */
async function reconcile(
  gh: Gh,
  record: IdeaRecord,
  body: string,
  at: { number: string; repo: string },
): Promise<SyncResult | undefined> {
  const title = record.title.trim();
  const issue = record.issue ?? "";
  const view = await gh([
    "issue",
    "view",
    at.number,
    "--repo",
    at.repo,
    "--json",
    "title,body",
  ]);
  if (view.code !== 0) {
    if (NOT_FOUND.test(view.stderr)) {
      return undefined;
    }
    throw failure(`gh could not read issue ${issue}`, view.stderr);
  }
  const current = parseView(view.stdout, issue);
  if (current.title.trim() === title && normal(current.body) === normal(body)) {
    return { action: "unchanged", issue };
  }
  const edit = await gh(
    [
      "issue",
      "edit",
      at.number,
      "--repo",
      at.repo,
      "--title",
      title,
      "--body-file",
      "-",
    ],
    body,
  );
  if (edit.code !== 0) {
    throw failure(`gh could not update issue ${issue}`, edit.stderr);
  }
  return { action: "updated", issue };
}

/**
 * Mirrors an idea to its GitHub issue in one direction. The issue is read only to
 * decide whether a write is needed; only the title and body are ever written, never
 * labels or assignees.
 */
export async function syncIssue(
  runner: Runner,
  root: string,
  record: IdeaRecord,
  text: string,
  recordLink: (url: string) => Promise<void>,
): Promise<SyncResult> {
  const body = renderBody(record, text);
  const gh: Gh = async (args, input) =>
    await runner.run("gh", args, {
      cwd: root,
      ...(input === undefined ? {} : { input }),
    });
  const at = record.issue === undefined ? undefined : locate(record.issue);
  if (record.issue !== undefined && at === undefined) {
    throw new IdeaError(
      `${record.path} has issue "${record.issue}", which is not an issue number or link; set it to e.g. 123 or https://github.com/<owner>/<repo>/issues/123.`,
    );
  }
  const repo = await resolveRepo(gh, at?.repo);
  const existing =
    at === undefined
      ? undefined
      : await reconcile(gh, record, body, { number: at.number, repo });
  if (existing !== undefined) {
    return existing;
  }
  const created = await gh(
    [
      "issue",
      "create",
      "--repo",
      repo,
      "--title",
      record.title.trim(),
      "--body-file",
      "-",
    ],
    body,
  );
  const url = ISSUE_URL.exec(created.stdout)?.[0];
  if (created.code !== 0) {
    throw failure("gh could not create the issue", created.stderr);
  }
  if (url === undefined) {
    throw new IdeaError(
      `gh reported success but printed no issue link, so the issue may exist: check the repository's issues for "${record.title.trim()}" in ${repo}, add \`issue: <url>\` to ${record.path}, then rerun \`harness idea sync\`; otherwise a duplicate is created.`,
    );
  }
  try {
    await recordLink(url);
  } catch (error) {
    throw new IdeaError(
      `Created ${url} but could not record it in ${record.path}: ${error instanceof Error ? error.message : String(error)}. Add \`issue: ${url}\` to its frontmatter, then rerun \`harness idea sync\`; otherwise a second issue is created.`,
    );
  }
  return { action: "created", issue: url };
}

function parseView(
  stdout: string,
  issue: string,
): { title: string; body: string } {
  try {
    const parsed = JSON.parse(stdout) as { title?: unknown; body?: unknown };
    return {
      title: typeof parsed.title === "string" ? parsed.title : "",
      body: typeof parsed.body === "string" ? parsed.body : "",
    };
  } catch {
    throw new IdeaError(
      `gh returned unreadable output for issue ${issue}; rerun \`harness idea sync\`.`,
    );
  }
}

/** The issue an idea is linked to, resolving the repository when the link is a bare number. */
export async function issueTarget(
  runner: Runner,
  root: string,
  record: IdeaRecord,
): Promise<{ number: string; repo: string }> {
  if (record.issue === undefined) {
    throw new IdeaError(
      `${record.path} has no issue; run \`harness idea sync --idea ${record.number}\` to create and link it first.`,
    );
  }
  const at = locate(record.issue);
  if (at === undefined) {
    throw new IdeaError(
      `${record.path} has issue "${record.issue}", which is not an issue number or link; set it to e.g. 123 or https://github.com/<owner>/<repo>/issues/123.`,
    );
  }
  const gh: Gh = async (args, input) =>
    await runner.run("gh", args, {
      cwd: root,
      ...(input === undefined ? {} : { input }),
    });
  return { number: at.number, repo: await resolveRepo(gh, at.repo) };
}
